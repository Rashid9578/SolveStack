CREATE TABLE tracker_owners (
    id UUID PRIMARY KEY,
    kind VARCHAR(8) NOT NULL,
    normalized_email VARCHAR(254) UNIQUE,
    password_hash VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tracker_owner_credentials CHECK (
        (kind = 'GUEST' AND normalized_email IS NULL AND password_hash IS NULL)
        OR
        (kind = 'ACCOUNT'
            AND normalized_email IS NOT NULL
            AND normalized_email <> ''
            AND normalized_email = lower(btrim(normalized_email))
            AND password_hash IS NOT NULL
            AND password_hash <> '')
    )
);

CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    accent TEXT NOT NULL CHECK (btrim(accent) <> ''),
    position INTEGER NOT NULL UNIQUE CHECK (position > 0)
);

CREATE TABLE problems (
    id TEXT PRIMARY KEY CHECK (btrim(id) <> ''),
    topic_id BIGINT NOT NULL REFERENCES topics(id),
    title TEXT NOT NULL CHECK (btrim(title) <> ''),
    external_url TEXT NOT NULL CHECK (external_url ~ '^https://[^[:space:]]+$'),
    position INTEGER NOT NULL CHECK (position > 0),
    UNIQUE (topic_id, position)
);

CREATE TABLE problem_completions (
    owner_id UUID NOT NULL REFERENCES tracker_owners(id) ON DELETE CASCADE,
    problem_id TEXT NOT NULL REFERENCES problems(id),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (owner_id, problem_id)
);

CREATE INDEX problem_completions_problem_idx ON problem_completions (problem_id);
